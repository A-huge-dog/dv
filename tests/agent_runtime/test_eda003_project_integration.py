class FakeUvmProvider:
    provider_id = "fake-uvm-provider"
    model_id = "openai/gpt-5.6-sol"

    def __init__(self):
        self.calls = 0
        self.requests = []

    def probe(self):
        return {
            "schema_version": "1.0", "provider_id": self.provider_id,
            "model_id": self.model_id, "status": "PASS",
            "tool_call_capable": True, "provider_version": "test",
            "diagnostics": [],
        }

    def restore_probe(self, _probe):
        return None

    def select_tools(self, request):
        self.calls += 1
        self.requests.append(copy.deepcopy(request))
        payload = json.loads(request["messages"][1]["content"])
        replacements = [{
            "logical_path": path,
            "content": "// generated by independent UVM role\n",
        } for path in payload["immutable_generation_context"][
            "generated_file_slots"]]
        prior_results = [
            json.loads(message["content"].split("\n", 1)[1])
            for message in request["messages"][2:]
            if message.get("role") == "USER" and
            message.get("content", "").startswith("TOOL_RESULT\n")
        ]
        if not prior_results:
            tool_name = "write_uvm_replacements"
            arguments = {"replacements": replacements}
        elif prior_results[-1]["tool_name"] == "write_uvm_replacements":
            tool_name, arguments = "run_xcelium_compile", {}
        else:
            tool_name, arguments = "finish_task", {}
        return {
            "schema_version": "1.0",
            "request_id": request["request_id"],
            "operation": "SELECT_TOOLS", "finish_reason": "TOOL_CALLS",
            "content": "", "model_id": self.model_id,
            "provider_metadata": {
                "provider_id": self.provider_id,
                "response_id": "RESP.UVM.{:03d}".format(self.calls),
                "provider_status": "completed",
            },
            "usage": {"input_tokens": 1, "output_tokens": 1},
            "diagnostics": [],
            "tool_calls": [{
                "call_id": "CALL.UVM.{:03d}".format(self.calls),
                "name": tool_name,
                "arguments": arguments,
            }],
        }


