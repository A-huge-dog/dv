    def test_generation_runner_builds_uvm_with_framework_elaboration_top(self):
        calls = []

        class Adapter:
            def build_only(self, execution_id, configuration):
                calls.append((execution_id, configuration))
                return {"execution_status": "PASS", "exit_code": 0}

        manifest = {
            "job_id": "JOB.PROJECT.TINY.EDA003",
            "rtl": {"sources": [{"baseline_path": "tiny.sv"}],
                    "top": "tiny"},
            "eda": {"timeout_seconds": 60},
        }
        request = {
            "cycle_id": "initial", "attempt": 1, "tool_run": 1,
            "sources": [{
                "logical_path": "uvm/pkg.sv",
                "path": "staging/generated/uvm/initial/attempt-001/effective/uvm/pkg.sv",
            }],
            "framework_sources": [{
                "logical_path":
                    "framework/dv_uvm_generation_elaboration_top.sv",
                "path": (
                    "audit/uvm_generation/initial/attempt-001/"
                    "xcelium-run-001.elaboration_top.sv"),
            }],
            "top": "dv_uvm_generation_elaboration_top",
        }
        with patch(
                "scripts.run_project_job.XceliumAdapter.from_preloaded_environment",
                return_value=Adapter()):
            generation_xcelium(manifest, Path("unused"), request)

        self.assertEqual(1, len(calls))
        configuration = calls[0][1]
        self.assertEqual(
            "dv_uvm_generation_elaboration_top", configuration.top)
        self.assertEqual((
            "result/jobs/JOB.PROJECT.TINY.EDA003/staging/generated/uvm/"
            "initial/attempt-001/effective/uvm/pkg.sv",
            "result/jobs/JOB.PROJECT.TINY.EDA003/audit/uvm_generation/"
            "initial/attempt-001/xcelium-run-001.elaboration_top.sv",
        ), configuration.sources)
        self.assertIn(
            "result/jobs/JOB.PROJECT.TINY.EDA003/staging/generated/uvm/"
            "initial/attempt-001/effective/uvm",
            configuration.include_dirs)
        self.assertNotIn("tiny.sv", configuration.sources)

    def test_independent_uvm_pass_tree_is_the_only_stage3_context(self):
        workspace_uvm_before = {
            path: (path.read_bytes(), path.stat().st_mtime_ns)
            for path in sorted((self.root / "uvm").rglob("*"))
            if path.is_file()
        }
        generator = Eda003Generator()
        reviewer = FakeReviewerProvider()
        uvm = FakeUvmProvider()
        repair_generator = Eda003RepairGenerator()
        workflow = ProjectJobWorkflow(
            self.root, self.root / "result",
            role_providers={
                "initial.stage1": generator, "initial.stage2": generator,
                "initial.uvm": uvm, "initial.stage3": generator,
                "repair.stage3": repair_generator,
                "review.initial": reviewer,
            },
            uvm_build_runner=lambda _value, _root, _request: {
                "execution_status": "PASS", "exit_code": 0,
                "stdout": "build passed", "stderr": "", "logs": [],
            })
        submission = {
            "schema_version": "2.0", "job_id": "JOB.PROJECT.TINY.EDA003",
            "project_id": "PROJECT.TINY", "spec": {"sources": ["spec.md"]},
            "rtl": {"sources": ["tiny.sv"], "top": "tiny", "parameters": {}},
            "uvm_testcase_context": {
                "files": ["uvm/pkg.sv", "uvm/base_test.svh"],
                "generated_files": ["uvm/base_test.svh"],
            },
            "agent_profile": "config/agents.yaml",
            "eda": {"profile_id": "EDAPROFILE.XCELIUM.PROJECT.V1",
                    "timeout_seconds": 60},
            "input_authority": {"actor_type": "HUMAN", "identity": "owner",
                "roles": ["SPEC_OWNER", "DESIGN_OWNER"], "decision": "APPROVE"},
        }
        first = workflow.start(submission)
        job = self.root / "result/jobs" / submission["job_id"]
        form = load_document(job / first["owner_review_path"])
        form["actor"]["identity"] = "owner"
        for scenario in form["scenarios"]:
            scenario["routing"]["destination"] = \
                "AC_TESTCASE_MAP_AND_TESTCASE"
        result = workflow.route_scenarios(submission, form)
        self.assertEqual("AWAITING_HUMAN_REVIEW", result["state"])
        self.assertEqual(3, uvm.calls)
        stage3_request = next(item for item in generator.requests
                              if item["metadata"]["stage"] == "TESTCASE")
        payload = json.loads(stage3_request["messages"][1]["content"])
        context = payload["uvm_testcase_context"]
        by_path = {item["logical_path"]: item["content"]
                   for item in context["files"]}
        self.assertEqual("// generated by independent UVM role\n",
                         by_path["uvm/base_test.svh"])
        self.assertEqual("package p; endpackage\n", by_path["uvm/pkg.sv"])
        self.assertNotIn("baseline_uvm_files", payload)
        self.assertEqual(
            context["effective_uvm_root"],
            result["bundle_fingerprints"]["effective_uvm"])
        self.assertTrue((job / "transcripts/uvm_generation/").is_dir())
        self.assertTrue((job / "transcripts/stage3/").is_dir())
        generator_calls = generator.calls
        replay = workflow.start(submission)
        self.assertEqual("AWAITING_HUMAN_REVIEW", replay["state"])
        self.assertEqual(
            context["effective_uvm_root"],
            replay["bundle_fingerprints"]["effective_uvm"])
        self.assertEqual(generator_calls, generator.calls)
        self.assertEqual(3, uvm.calls)

        manifest = load_document(
            job / "input_baseline/project_input_manifest.json")
        map1 = load_document(job / result["scenario_ac_map_path"])
        map2 = load_document(job / result["ac_testcase_map_path"])
        candidate = load_document(job / result["candidate_metadata_path"])
        staged = StagedProjectWorkflow(workflow)
        spec_evidence, _, spec_fingerprint = staged._spec(manifest)
        testcases, shards = staged._load_shards(job, map2)
        effective_files, effective_root = load_effective_uvm_pass(
            job, job_id=manifest["job_id"],
            input_fingerprint=manifest["input_fingerprint"],
            cycle_id="initial", stage2_root=map2["artifact_fingerprint"],
            error=ProjectJobError)
        workflow._probe_provider(job, "repair.stage3")
        repaired = staged.generate_stage3_handler.handle(GenerateStage3Input(
            manifest, job, spec_evidence, spec_fingerprint, map1, map2,
            testcases, shards, 1, workflow._budget(), prior=candidate,
            issues=[{"finding_id": "F.REPAIR", "stage": "STAGE_3"}],
            effective_uvm_files=effective_files,
            effective_uvm_root=effective_root,
            profile_section="repair"))
        self.assertEqual(1, repaired.artifact["revision"])
        self.assertEqual("fake-repair-provider",
                         repaired.artifact["provider"]["provider_id"])
        self.assertEqual("repair.stage3",
            repair_generator.requests[-1]["metadata"]["agent_profile_role"])
        self.assertEqual(workspace_uvm_before, {
            path: (path.read_bytes(), path.stat().st_mtime_ns)
            for path in sorted((self.root / "uvm").rglob("*"))
            if path.is_file()
        })


