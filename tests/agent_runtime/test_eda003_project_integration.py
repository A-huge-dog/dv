class Eda003Generator(FakeProvider):
    @staticmethod
    def stage3(payload):
        manifest = payload["generated_testcase_manifest"]
        units = []
        implemented = []
        for item in manifest["testcases"]:
            testcase_id = item["testcase_id"]
            implemented.append(testcase_id)
            units.append({
                "role": "TESTCASE", "testcase_ids": [testcase_id],
                "content": (
                    "class {name} extends base_test;\n"
                    "  task execute_testcase();\n"
                    "    logic clk; logic y;\n"
                    "    clk = 1'b0; if (y !== clk) `uvm_fatal(\"AC_TINY_LOW_FAIL\", \"y\")\n"
                    "    clk = 1'b1; if (y !== clk) `uvm_fatal(\"AC_TINY_HIGH_FAIL\", \"y\")\n"
                    "  endtask\nendclass\n").format(name=item["uvm_class"]),
            })
        return {"code_units": units, "assembly": list(range(len(units))),
                "implemented_testcase_ids": implemented,
                "skipped_testcases": []}


